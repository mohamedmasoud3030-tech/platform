/**
 * Self-host the Arabic and Latin webfonts.
 *
 * The public site loaded five families from Google Fonts on every visit: two of
 * them were only ever fallback names in a font stack, and all five arrived from
 * a third party on the critical path — the exact thing a house that sells "what
 * you see is what runs" should not depend on for its own typography.
 *
 * This script fetches the three families the design system actually specifies
 * (Inter for Latin, IBM Plex Sans Arabic for Arabic body, Noto Kufi Arabic for
 * Arabic headings), keeps the arabic + latin subsets of each weight, writes them
 * into `public/fonts/`, and generates `src/styles/fonts.css` with the same
 * `unicode-range` declarations Google served — so the browser still downloads
 * only the subset a page needs, now from our own origin.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const fontDir = join(root, "public", "fonts");
const cssOut = join(root, "src", "styles", "fonts.css");

// A modern browser UA is required: Google serves woff2 only to clients that
// advertise support, and the legacy paths return ttf files three times larger.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const FAMILIES = [
  // Variable where the family offers it: one file covers every weight the CSS
  // asks for, instead of one file per weight.
  { query: "Inter:wght@400..700", slug: "inter", keep: ["latin"] },
  // IBM Plex Sans Arabic ships static instances only. 300 was in the original
  // import and is asked for by no rule in the stylesheets, so it is not fetched.
  { query: "IBM+Plex+Sans+Arabic:wght@400;500;600;700", slug: "plex-arabic", keep: ["arabic", "latin"] },
  { query: "Noto+Kufi+Arabic:wght@400..700", slug: "kufi-arabic", keep: ["arabic", "latin"] },
];

const HEADERS = { "User-Agent": UA };

async function fetchText(url) {
  const response = await fetch(url, { headers: HEADERS });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return response.text();
}

/** Split a Google CSS payload into @font-face blocks plus their /* subset *\/ comment. */
function parseFaces(css) {
  const faces = [];
  const pattern = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let match;
  while ((match = pattern.exec(css)) !== null) {
    const [, subset, block] = match;
    const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
    // A variable face declares a range ("font-weight: 100 900"); a static one a
    // single number. Both must survive into the generated CSS verbatim.
    const weight = /font-weight:\s*([\d\s]+);/.exec(block)?.[1]?.trim().replace(/\s+/g, " ");
    const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    const unicodeRange = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim();
    const style = /font-style:\s*([a-z]+)/.exec(block)?.[1] ?? "normal";
    if (family && weight && url) faces.push({ subset, family, weight, url, unicodeRange, style });
  }
  return faces;
}

const totals = { files: 0, bytes: 0 };
const out = [
  "/*",
  "   Self-hosted webfonts. Generated by scripts/fetch-fonts.mjs — do not edit by hand.",
  "",
  "   Only the three families the design system names are shipped, and only the",
  "   arabic + latin subsets of each weight, with the original unicode-range so a",
  "   page still downloads nothing it does not render. Fallback names in the font",
  "   stacks (Noto Sans Arabic, Noto Naskh Arabic) are left as stack entries: the",
  "   system font serves them if a device has one, with no network cost at all.",
  "*/",
  "",
];

for (const family of FAMILIES) {
  const css = await fetchText(
    `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`,
  );
  const faces = parseFaces(css).filter((face) => family.keep.includes(face.subset));
  if (faces.length === 0) throw new Error(`no faces parsed for ${family.family}`);

  for (const face of faces) {
    const response = await fetch(face.url, { headers: HEADERS });
    if (!response.ok) throw new Error(`${response.status} for ${face.url}`);
    const buffer = Buffer.from(await response.arrayBuffer());
    const name = `${family.slug}-${face.weight.replace(/\s+/g, "_")}-${face.subset}.woff2`;
    await mkdir(fontDir, { recursive: true });
    await writeFile(join(fontDir, name), buffer);
    totals.files += 1;
    totals.bytes += buffer.byteLength;

    out.push(
      "@font-face {",
      `  font-family: "${face.family}";`,
      `  font-style: ${face.style};`,
      `  font-weight: ${face.weight};`,
      "  font-display: swap;",
      `  src: url("/fonts/${name}") format("woff2");`,
      face.unicodeRange ? `  unicode-range: ${face.unicodeRange};` : null,
      "}",
      "",
    );
  }
  console.log(`${family.slug}: ${faces.length} face(s)`);
}

await writeFile(cssOut, out.filter((line) => line !== null).join("\n"), "utf8");
console.log(
  `wrote ${totals.files} woff2 files, ${(totals.bytes / 1024).toFixed(0)} KiB total → public/fonts + src/styles/fonts.css`,
);
void dirname;
